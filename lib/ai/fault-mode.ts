// Режим збою моделі (практична робота 6): перевірка відмов без справжнього збою провайдера.
// Змініть значення AI_FAULT_MODE, збережіть файл (Ctrl+S) і повторіть дію в браузері:
//   "none"    — звичайна робота;
//   "slow"    — провайдер «думає» 60 секунд (видно, чи спрацьовує ваш таймаут);
//   "down"    — провайдер недоступний (помилка 503);
//   "invalid" — провайдер відповідає текстом, який не відповідає вашій схемі.
// Перед кожним комітом поверніть "none". Під час тестів (npm test) режим не діє.
export type AiFaultMode = "none" | "slow" | "down" | "invalid";
export const AI_FAULT_MODE: AiFaultMode = "none";
